export const LANGS = ["en", "bn"];
let lang = "en";

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = LANGS.includes(next) ? next : "en";
  document.documentElement.lang = lang;
}

export function tr(key, vars = {}) {
  const entry = STRINGS[key];
  if (!entry) return key;
  let text = entry[lang] ?? entry.en;
  if (Array.isArray(text)) text = vars.n === 1 ? text[0] : text[1];
  return String(text).replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

// Fills every element of the page that carries data-i18n (text) or data-i18n-attr ("attr:key;attr:key").
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = tr(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    el.dataset.i18nAttr.split(";").forEach((pair) => {
      const [attr, key] = pair.split(":");
      if (attr && key) el.setAttribute(attr, tr(key));
    });
  });
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.content = tr("app.desc");
}
